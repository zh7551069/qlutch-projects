  go: '// Code generated by tools/codegen from packages/contracts/openapi.yaml. DO NOT EDIT.\n\n',
  ts: '// Code generated by tools/codegen from packages/contracts/openapi.yaml. DO NOT EDIT.\n\n',
  swift: '// Code generated by tools/codegen from packages/contracts/openapi.yaml. DO NOT EDIT.\n\n',
  kotlin: '// Code generated by tools/codegen from packages/contracts/openapi.yaml. DO NOT EDIT.\n\n',
