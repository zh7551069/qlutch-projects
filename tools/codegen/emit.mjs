export function emitGo(model) {
  const structs = model.schemas.map((schema) => {
    const fields = schema.fields
      .map((field) => `\t${field.goName} ${goFieldType(field)} \`json:"${jsonTag(field)}"\``)
      .join('\n')
    return `type ${schema.name} struct {\n${fields}\n}`
  })
  const methods = model.operations
    .map(
      (operation) =>
        `func (c *Client) ${operation.goName}(ctx context.Context) (APIResponse[${operation.responseName}], error) {\n\treturn doJSON[${operation.responseName}](ctx, c, http.Method${exportWord(operation.method)}, "${operation.path}")\n}`,
    )
    .join('\n\n')
  return `${header.go}package qlutchapi

import (
	"context"
	"encoding/json"
	"io"
	"net/http"
	"strings"
)

type APIResponse[T any] struct {
	StatusCode int
	Body       T
	RequestID  string
}

type Client struct {
	BaseURL string
	HTTP    *http.Client
}

${structs.join('\n\n')}

${methods}

func doJSON[T any](ctx context.Context, client *Client, method, path string) (APIResponse[T], error) {
	var zero APIResponse[T]
	if client == nil || client.BaseURL == "" {
		return zero, errString("missing base url")
	}
	endpoint := strings.TrimRight(client.BaseURL, "/") + path
	req, err := http.NewRequestWithContext(ctx, method, endpoint, nil)
	if err != nil {
		return zero, err
	}
	req.Header.Set("Accept", "application/json")
	httpClient := client.HTTP
	if httpClient == nil {
		httpClient = http.DefaultClient
	}
	resp, err := httpClient.Do(req)
	if err != nil {
		return zero, err
	}
	defer resp.Body.Close()
	payload, err := io.ReadAll(io.LimitReader(resp.Body, 1<<20))
	if err != nil {
		return zero, err
	}
	var decoded T
	if err := json.Unmarshal(payload, &decoded); err != nil {
		return zero, err
	}
	return APIResponse[T]{
		StatusCode: resp.StatusCode,
		Body:       decoded,
		RequestID:  resp.Header.Get("X-Request-Id"),
	}, nil
}

type errString string

func (e errString) Error() string { return string(e) }
`
}

export function emitTS(model) {
  const interfaces = model.schemas
    .map((schema) => {
      const fields = schema.fields
        .map((field) => `  ${field.jsonName}${field.required ? '' : '?'}: ${tsType(field.type)}`)
        .join('\n')
      return `export interface ${schema.name} {\n${fields}\n}`
    })
    .join('\n\n')
  const methods = model.operations
    .map(
      (operation) =>
        `  ${operation.operationId}(init?: { signal?: AbortSignal }): Promise<ApiResponse<${operation.responseName}>> {\n    return this.request<${operation.responseName}>('${operation.method}', '${operation.path}', init)\n  }`,
    )
    .join('\n\n')
  return `${header.ts}${interfaces}

export interface ApiResponse<T> {
  status: number
  body: T
  requestId: string
}

export class QlutchClient {
  constructor(
    private readonly baseUrl: string,
    private readonly fetchImpl: typeof fetch = fetch,
  ) {}

${methods}

  private async request<T>(method: string, path: string, init?: { signal?: AbortSignal }): Promise<ApiResponse<T>> {
    const response = await this.fetchImpl.call(globalThis, joinURL(this.baseUrl, path), {
      method,
      headers: { Accept: 'application/json' },
      signal: init?.signal,
    })
    const body = (await response.json()) as T
    return {
      status: response.status,
      body,
      requestId: response.headers.get('x-request-id') ?? '',
    }
  }
}

function joinURL(baseURL: string, path: string): string {
  return baseURL.replace(/\\/$/, '') + path
}
`
}

export function emitSwift(model) {
  const structs = model.schemas
    .map((schema) => {
      const fields = schema.fields
        .map((field) => `    public let ${field.jsonName}: ${swiftType(field.type)}${field.required ? '' : '?'}`)
        .join('\n')
      return `public struct ${schema.name}: Decodable, Sendable {\n${fields}\n}`
    })
    .join('\n\n')
  const methods = model.operations
    .map(
      (operation) =>
        `    public func ${operation.operationId}() async throws -> APIResponse<${operation.responseName}> {\n        try await request(method: "${operation.method}", path: "${operation.path}")\n    }`,
    )
    .join('\n\n')
  return `${header.swift}import Foundation

public struct APIResponse<Body: Decodable & Sendable>: Sendable {
    public let statusCode: Int
    public let body: Body
    public let requestID: String
}

${structs}

public enum QlutchClientError: Error {
    case badURL
    case notHTTP
}

public struct QlutchClient: Sendable {
    public var baseURL: URL
    public var session: URLSession

    public init(baseURL: URL, session: URLSession = .shared) {
        self.baseURL = baseURL
        self.session = session
    }

${methods}

    private func request<T: Decodable>(method: String, path: String) async throws -> APIResponse<T> {
        let root = baseURL.absoluteString.hasSuffix("/") ? String(baseURL.absoluteString.dropLast()) : baseURL.absoluteString
        guard let url = URL(string: root + path) else {
            throw QlutchClientError.badURL
        }
        var request = URLRequest(url: url)
        request.httpMethod = method
        request.setValue("application/json", forHTTPHeaderField: "Accept")
        let (data, response) = try await session.data(for: request)
        guard let http = response as? HTTPURLResponse else {
            throw QlutchClientError.notHTTP
        }
        let body = try JSONDecoder().decode(T.self, from: data)
        return APIResponse(
            statusCode: http.statusCode,
            body: body,
            requestID: http.value(forHTTPHeaderField: "X-Request-Id") ?? ""
        )
    }
}
`
}

export function emitKotlin(model) {
  const classes = model.schemas
    .map((schema) => {
      const params = schema.fields
        .map((field) => `    val ${field.jsonName}: ${kotlinType(field.type)}${field.required ? '' : '?'}`)
        .join(',\n')
      const args = schema.fields.map((field) => kotlinRead(field)).join(',\n        ')
      return `class ${schema.name}(\n${params}\n)

fun parse${schema.name}(text: String): ${schema.name} {
    val root = JSONObject(text)
    return ${schema.name}(
        ${args}
    )
}`
    })
    .join('\n\n')
  const methods = model.operations
    .map(
      (operation) =>
        `    fun ${operation.operationId}(): ApiResponse<${operation.responseName}> {\n        val raw = request("${operation.method}", "${operation.path}")\n        return ApiResponse(raw.statusCode, parse${operation.responseName}(raw.text), raw.requestId)\n    }`,
    )
    .join('\n\n')
  return `${header.kotlin}package dev.qlutch.contract

import java.net.HttpURLConnection
import java.net.URI
import org.json.JSONObject

class ApiResponse<T>(val statusCode: Int, val body: T, val requestId: String)

private class RawResponse(val statusCode: Int, val text: String, val requestId: String)

${classes}

class QlutchClient(private val baseUrl: String) {
${methods}

    private fun request(method: String, path: String): RawResponse {
        val connection = (URI(baseUrl.trimEnd('/') + path).toURL().openConnection() as HttpURLConnection)
        try {
            connection.requestMethod = method
            connection.setRequestProperty("Accept", "application/json")
            connection.connectTimeout = 5000
            connection.readTimeout = 5000
            val code = connection.responseCode
            val stream = if (code >= 400) connection.errorStream else connection.inputStream
            val text = stream?.bufferedReader()?.use { it.readText() } ?: ""
            val requestId = connection.getHeaderField("X-Request-Id") ?: ""
            return RawResponse(code, text, requestId)
        } finally {
            connection.disconnect()
        }
    }
}

private fun readStringMap(root: JSONObject, name: String): Map<String, String>? {
    if (!root.has(name) || root.isNull(name)) return null
    val obj = root.getJSONObject(name)
    val out = linkedMapOf<String, String>()
    val keys = obj.keys()
    while (keys.hasNext()) {
        val key = keys.next()
        out[key] = obj.getString(key)
    }
    return out
}
`
}

export function emitArkTS(model) {
  const classes = model.schemas
    .map((schema) => {
      const fields = schema.fields
        .map((field) => {
          if (field.type.kind === 'map') {
            return `  ${field.jsonName}: Record<string, string> | null = null`
          }
          const initial = field.type.kind === 'string' ? "''" : field.type.kind === 'boolean' ? 'false' : '0'
          return `  ${field.jsonName}: ${arkType(field.type)} = ${initial}`
        })
        .join('\n')
      return `export class ${schema.name} {\n${fields}\n}`
    })
    .join('\n\n')
  const results = model.operations
    .map(
      (operation) => `export class ${operation.goName}Result {
  statusCode: number = 0
  requestId: string = ''
  body: ${operation.responseName} = new ${operation.responseName}()
}`,
    )
    .join('\n\n')
  const functions = model.operations
    .map(
      (operation) => `export function ${operation.operationId}(baseUrl: string): Promise<${operation.goName}Result> {
  return request(joinURL(baseUrl, '${operation.path}'), http.RequestMethod.${operation.method}).then((response: http.HttpResponse) => {
    const result = new ${operation.goName}Result()
    result.statusCode = response.responseCode
    const header = response.header['X-Request-Id']
    if (header !== undefined && header !== null) {
      result.requestId = String(header)
    }
    const parsed = JSON.parse(response.result.toString()) as Record<string, Object>
    result.body = read${operation.responseName}(parsed)
    return result
  })
}`,
    )
    .join('\n\n')
  const readers = model.schemas
    .map((schema) => {
      const lines = schema.fields.map((field) => {
        if (field.type.kind === 'map' && field.type.value.kind === 'string') {
          return `  body.${field.jsonName} = readStringMap(parsed['${field.jsonName}'])`
        }
        return `  const ${field.jsonName}Value = parsed['${field.jsonName}']
  if (${field.jsonName}Value !== undefined && ${field.jsonName}Value !== null) {
    body.${field.jsonName} = ${field.jsonName}Value as ${arkType(field.type)}
  }`
      })
      return `function read${schema.name}(parsed: Record<string, Object>): ${schema.name} {
  const body = new ${schema.name}()
${lines.join('\n')}
  return body
}`
    })
    .join('\n\n')
  return `${header.ets}import { http } from '@kit.NetworkKit'

${classes}

${results}

${functions}

function request(url: string, method: http.RequestMethod): Promise<http.HttpResponse> {
  return new Promise((resolve: (value: http.HttpResponse) => void, reject: (reason: Error) => void) => {
    const client = http.createHttp()
    client.request(url, {
      method: method,
      header: { 'Accept': 'application/json' },
      connectTimeout: 5000,
      readTimeout: 5000,
      expectDataType: http.HttpDataType.STRING
    }, (err: Error, response: http.HttpResponse) => {
      client.destroy()
      if (err) {
        reject(err)
        return
      }
      resolve(response)
    })
  })
}

function joinURL(baseUrl: string, path: string): string {
  let trimmed = baseUrl
  if (trimmed.endsWith('/')) {
    trimmed = trimmed.substring(0, trimmed.length - 1)
  }
  return trimmed + path
}

${readers}

function readStringMap(value: Object | undefined): Record<string, string> | null {
  if (value === undefined || value === null) {
    return null
  }
  return value as Record<string, string>
}
`
}

function jsonTag(field) {
  return field.required ? field.jsonName : `${field.jsonName},omitempty`
}

function goFieldType(field) {
  const base = goType(field.type)
  if (!field.required && field.type.kind !== 'array' && field.type.kind !== 'map') {
    return `*${base}`
  }
  return base
}

function goType(type) {
  switch (type.kind) {
    case 'string':
      return 'string'
    case 'integer':
      return 'int64'
    case 'number':
      return 'float64'
    case 'boolean':
      return 'bool'
    case 'ref':
      return type.name
    case 'array':
      return `[]${goType(type.item)}`
    case 'map':
      return `map[string]${goType(type.value)}`
    default:
      throw new Error(`unsupported Go type ${type.kind}`)
  }
}

function tsType(type) {
  switch (type.kind) {
    case 'string':
      return 'string'
    case 'integer':
    case 'number':
      return 'number'
    case 'boolean':
      return 'boolean'
    case 'ref':
      return type.name
    case 'array':
      return `${tsType(type.item)}[]`
    case 'map':
      return `Record<string, ${tsType(type.value)}>`
    default:
      throw new Error(`unsupported TypeScript type ${type.kind}`)
  }
}

function swiftType(type) {
  switch (type.kind) {
    case 'string':
      return 'String'
    case 'integer':
      return 'Int'
    case 'number':
      return 'Double'
    case 'boolean':
      return 'Bool'
    case 'ref':
      return type.name
    case 'array':
      return `[${swiftType(type.item)}]`
    case 'map':
      return `[String: ${swiftType(type.value)}]`
    default:
      throw new Error(`unsupported Swift type ${type.kind}`)
  }
}

function kotlinType(type) {
  switch (type.kind) {
    case 'string':
      return 'String'
    case 'integer':
      return 'Long'
    case 'number':
      return 'Double'
    case 'boolean':
      return 'Boolean'
    case 'ref':
      return type.name
    case 'array':
      return `List<${kotlinType(type.item)}>`
    case 'map':
      return `Map<String, ${kotlinType(type.value)}>`
    default:
      throw new Error(`unsupported Kotlin type ${type.kind}`)
  }
}

function kotlinRead(field) {
  if (field.type.kind === 'map' && field.type.value.kind === 'string') {
    return `readStringMap(root, "${field.jsonName}")`
  }
  const read = kotlinScalar(field)
  if (!field.required) {
    return `if (root.has("${field.jsonName}") && !root.isNull("${field.jsonName}")) ${read} else null`
  }
  return read
}

function kotlinScalar(field) {
  const name = field.jsonName
  switch (field.type.kind) {
    case 'string':
      return `root.getString("${name}")`
    case 'integer':
      return `root.getLong("${name}")`
    case 'number':
      return `root.getDouble("${name}")`
    case 'boolean':
      return `root.getBoolean("${name}")`
    default:
      throw new Error(`unsupported Kotlin field ${name}`)
  }
}

function arkType(type) {
  switch (type.kind) {
    case 'string':
      return 'string'
    case 'integer':
    case 'number':
      return 'number'
    case 'boolean':
      return 'boolean'
    case 'ref':
      return type.name
    case 'array':
      return `Array<${arkType(type.item)}>`
    case 'map':
      return 'Record<string, string>'
    default:
      throw new Error(`unsupported ArkTS type ${type.kind}`)
  }
}

function exportWord(method) {
  const lower = method.toLowerCase()
  return lower.slice(0, 1).toUpperCase() + lower.slice(1)
}
