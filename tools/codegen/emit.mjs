function emitKotlinClass(model, byName, schema) {
  if (schema.fields.length === 0) {
    return `class ${schema.name} {
    fun toJSON(): JSONObject {
        return JSONObject()
    }
}

fun parse${schema.name}(text: String): ${schema.name} {
    return parse${schema.name}Object(JSONObject(text))
}

fun parse${schema.name}Object(root: JSONObject): ${schema.name} {
    return ${schema.name}()
}`
  }
  const params = schema.fields
    .map((field) => `    val ${field.jsonName}: ${kotlinFieldType(model, field)}`)
    .join(',\n')
  const reads = schema.fields.map((field) => kotlinRead(model, byName, schema, field)).join(',\n        ')
  const writes = schema.fields
    .map((field) => kotlinWrite(model, field))
    .filter(Boolean)
    .join('\n    ')
  return `class ${schema.name}(
${params}
) {
    fun toJSON(): JSONObject {
        val out = JSONObject()
        ${writes}
        return out
    }
}

fun parse${schema.name}(text: String): ${schema.name} {
    return parse${schema.name}Object(JSONObject(text))
}

fun parse${schema.name}Object(root: JSONObject): ${schema.name} {
    return ${schema.name}(
        ${reads}
    )
}`
}

function kotlinWrite(model, field) {
  const type = field.type
  if (!field.required || field.nullable) {
    if (type.kind === 'ref' && schemaByName(model, type.name).kind === 'object') {
      return `if (${field.jsonName} != null) out.put("${field.jsonName}", ${field.jsonName}.toJSON())`
    }
    if (type.kind === 'array') {
      return `if (${field.jsonName} != null) out.put("${field.jsonName}", JSONArray(${field.jsonName}))`
    }
    return `if (${field.jsonName} != null) out.put("${field.jsonName}", ${field.jsonName})`
  }
  if (type.kind === 'ref' && schemaByName(model, type.name).kind === 'object') {
    return `out.put("${field.jsonName}", ${field.jsonName}.toJSON())`
  }
  return `out.put("${field.jsonName}", ${field.jsonName})`
}

function kotlinRead(model, byName, schema, field) {
  const expr = kotlinRequiredRead(model, field)
  if (!field.required || field.nullable) {
    return `if (root.has("${field.jsonName}") && !root.isNull("${field.jsonName}")) ${expr} else null`
  }
  return expr
}

function kotlinArrayReaders(model) {
  return arrayReaderNames(model)
    .map(
      (name) => `private fun read${name}Array(root: JSONObject, name: String): List<${name}> {
    if (!root.has(name) || root.isNull(name)) return emptyList()
    val arr = root.getJSONArray(name)
    val out = ArrayList<${name}>()
    for (i in 0 until arr.length()) {
        out.add(parse${name}Object(arr.getJSONObject(i)))
    }
    return out
}

`,
    )
    .join('')
}

function kotlinRequiredRead(model, field) {
  const type = field.type
  switch (type.kind) {
    case 'string':
      return `root.getString("${field.jsonName}")`
    case 'integer':
      return `root.getLong("${field.jsonName}")`
    case 'number':
      return `root.getDouble("${field.jsonName}")`
    case 'boolean':
      return `root.getBoolean("${field.jsonName}")`
    case 'json':
      return `root.get("${field.jsonName}").toString()`
    case 'map':
      return `readStringMap(root, "${field.jsonName}") ?: emptyMap()`
    case 'ref': {
      const target = schemaByName(model, type.name)
      if (target.kind === 'alias') return `root.getString("${field.jsonName}")`
      return `parse${type.name}Object(root.getJSONObject("${field.jsonName}"))`
    }
    case 'array':
      return `read${type.item.kind === 'ref' ? type.item.name : 'Value'}Array(root, "${field.jsonName}")`
    default:
      throw new Error(`unsupported Kotlin field ${field.jsonName}`)
  }
}

export function emitArkTS(model) {
  const classes = model.schemas
    .filter((schema) => schema.kind === 'object')
    .map((schema) => {
      const fields = schema.fields
        .map((field) => `  ${field.jsonName}: ${arkFieldType(model, field)} = ${arkInitial(model, field)}`)
        .join('\n')
      return `export class ${schema.name} {\n${fields}\n}`
    })
    .join('\n\n')
  const aliasConstants = model.schemas
    .filter((schema) => schema.kind === 'alias')
    .map((schema) => {
      const lines = schema.enumValues
        .map((value) => `  static readonly ${enumConstName(schema.name, value)}: string = ${JSON.stringify(value)}`)
        .join('\n')
      return `export class ${schema.name}Values {\n${lines}\n}`
    })
    .join('\n\n')
  const results = model.operations
    .map((operation) => {
      const response = operation.responseName ?? 'Empty'
      return `export class ${operation.goName}Result {
  statusCode: number = 0
  requestId: string = ''
  body: ${response} = new ${response}()
}`
    })
    .join('\n\n')
  const functions = model.operations
    .map((operation) => emitArkFunction(model, operation))
    .join('\n\n')
  const writers = [
    ...new Set(model.operations.map((operation) => operation.bodyName).filter(Boolean)),
  ]
    .map((name) => `function write${name}(body: ${name}): string {\n  return JSON.stringify(body)\n}`)
    .join('\n\n')
  const readers = model.schemas
    .filter((schema) => schema.kind === 'object')
    .map((schema) => emitArkReader(model, schema))
    .join('\n\n')
  const arrayReaders = arrayReaderNames(model)
    .map((name) => emitArkArrayReader(name))
    .join('\n\n')
  return `${header.ets}import { http } from '@kit.NetworkKit'

${aliasConstants}

${classes}

export class Empty {}

${results}

${functions}

${writers}

function readEmpty(_parsed: Record<string, Object>): Empty {
  return new Empty()
}

class RequestExtra {
  body: string = ''
  idempotencyKey: string = ''
  requestId: string = ''
  bearer: string = ''
}

function request(url: string, method: http.RequestMethod, extra?: RequestExtra | null): Promise<http.HttpResponse> {
  return new Promise((resolve: (value: http.HttpResponse) => void, reject: (reason: Error) => void) => {
    const client = http.createHttp()
    const header: Record<string, string> = { 'Accept': 'application/json' }
    let data = ''
    if (extra !== undefined && extra !== null) {
      if (extra.body.length > 0) {
        header['Content-Type'] = 'application/json'
        data = extra.body
      }
      if (extra.idempotencyKey.length > 0) {
        header['Idempotency-Key'] = extra.idempotencyKey
      }
      if (extra.requestId.length > 0) {
        header['X-Request-Id'] = extra.requestId
      }
      if (extra.bearer.length > 0) {
        header['Authorization'] = 'Bearer ' + extra.bearer
      }
    }
    client.request(url, {
      method: method,
      header: header,
      extraData: data,
      connectTimeout: 5000,
      readTimeout: 5000,
      expectDataType: http.HttpDataType.STRING
    }, (err: Error, response: http.HttpResponse) => {
      client.destroy()
      if (err) {
        reject(err)
        return
      }
      resolve(response)
    })
  })
}

function joinURL(baseUrl: string, path: string): string {
  let trimmed = baseUrl
  if (trimmed.endsWith('/')) {
    trimmed = trimmed.substring(0, trimmed.length - 1)
  }
  return trimmed + path
}

${readers}

${arrayReaders}

function readStringMap(value: Object | undefined): Record<string, string> | null {
  if (value === undefined || value === null) {
    return null
  }
  return value as Record<string, string>
}

function readJSONText(value: Object | undefined): string {
  if (value === undefined || value === null) {
    return ''
  }
  return JSON.stringify(value)
}
`
}

function emitArkFunction(model, operation) {
  const response = operation.responseName ?? 'Empty'
  const args = ['baseUrl: string', ...pathParamArgs(operation, 'ark')]
  if (headerPresent(operation, 'Idempotency-Key')) args.push('idempotencyKey: string')
  if (operation.bodyName) {
    args.push(operation.bodyRequired ? `body: ${operation.bodyName}` : `body: ${operation.bodyName} | null`)
  }
  if (headerPresent(operation, 'X-Request-Id')) args.push('requestId?: string')
  if (operation.auth !== 'none') args.push('bearer?: string')
  const extra = []
  if (operation.bodyName) {
    extra.push(`  if (body !== undefined && body !== null) {\n    extra.body = write${operation.bodyName}(body)\n  }`)
  }
  if (headerPresent(operation, 'Idempotency-Key')) extra.push('  extra.idempotencyKey = idempotencyKey')
  if (headerPresent(operation, 'X-Request-Id')) {
    extra.push(`  if (requestId !== undefined && requestId !== null) {\n    extra.requestId = requestId\n  }`)
  }
  if (operation.auth !== 'none') {
    extra.push(`  if (bearer !== undefined && bearer !== null) {\n    extra.bearer = bearer\n  }`)
  }
  return `export function ${operation.operationId}(${args.join(', ')}): Promise<${operation.goName}Result> {
  const extra = new RequestExtra()
${extra.join('\n')}
  return request(joinURL(baseUrl, ${arkPathExpr(operation)}), http.RequestMethod.${operation.method}, extra).then((response: http.HttpResponse) => {
    const result = new ${operation.goName}Result()
    result.statusCode = response.responseCode
    const header = response.header['X-Request-Id']
    if (header !== undefined && header !== null) {
      result.requestId = String(header)
    }
    if (response.responseCode === 204) {
      return result
    }
    const parsed = JSON.parse(response.result.toString()) as Record<string, Object>
    result.body = read${response}(parsed)
    return result
  })
}`
}

function emitArkReader(model, schema) {
  const lines = schema.fields.map((field) => {
    if (field.type.kind === 'map' && field.type.value.kind === 'string') {
      return `  body.${field.jsonName} = readStringMap(parsed['${field.jsonName}'])`
    }
    if (field.type.kind === 'json') {
      return `  body.${field.jsonName} = readJSONText(parsed['${field.jsonName}'])`
    }
    if (field.type.kind === 'array' && field.type.item.kind === 'ref') {
      return `  body.${field.jsonName} = read${field.type.item.name}Array(parsed['${field.jsonName}'])`
    }
    if (field.type.kind === 'ref' && schemaByName(model, field.type.name).kind === 'object') {
      return `  const ${field.jsonName}Value = parsed['${field.jsonName}']
  if (${field.jsonName}Value !== undefined && ${field.jsonName}Value !== null) {
    body.${field.jsonName} = read${field.type.name}(${field.jsonName}Value as Record<string, Object>)
  }`
    }
    return `  const ${field.jsonName}Value = parsed['${field.jsonName}']
  if (${field.jsonName}Value === null) {
    body.${field.jsonName} = ${arkNullValue(model, field)}
  } else if (${field.jsonName}Value !== undefined) {
    body.${field.jsonName} = ${field.jsonName}Value as ${arkCastType(model, field)}
  }`
  })
  return `function read${schema.name}(parsed: Record<string, Object>): ${schema.name} {
  const body = new ${schema.name}()
${lines.join('\n')}
  return body
}`
}

function emitArkArrayReader(name) {
  return `function read${name}Array(value: Object | undefined): Array<${name}> {
  const out = new Array<${name}>()
  if (value === undefined || value === null) {
    return out
  }
  const items = value as Array<Record<string, Object>>
  for (let index = 0; index < items.length; index++) {
    out.push(read${name}(items[index]))
  }
  return out
}`
}

function arrayReaderNames(model) {
  const names = new Set()
  for (const schema of model.schemas) {
    if (schema.kind !== 'object') continue
    for (const field of schema.fields) {
      if (field.type.kind === 'array' && field.type.item.kind === 'ref') names.add(field.type.item.name)
    }
  }
  return [...names]
}

function arkFieldType(model, field) {
  const base = arkTypeOf(model, field.type)
  if (field.nullable) return `${base} | null`
  return base
}

function arkCastType(model, field) {
  return arkTypeOf(model, field.type)
}

function arkTypeOf(model, type) {
  switch (type.kind) {
    case 'string':
    case 'json':
      return 'string'
    case 'integer':
    case 'number':
      return 'number'
    case 'boolean':
      return 'boolean'
    case 'ref':
      return schemaByName(model, type.name).kind === 'alias' ? 'string' : type.name
    case 'array':
      return `Array<${type.item.kind === 'ref' ? type.item.name : arkTypeOf(model, type.item)}>`
    case 'map':
      return 'Record<string, string> | null'
    default:
      throw new Error(`unsupported ArkTS type ${type.kind}`)
  }
}

function arkInitial(model, field) {
  if (field.nullable) return 'null'
  if (field.type.kind === 'string' || field.type.kind === 'json') return "''"
  if (field.type.kind === 'boolean') return 'false'
  if (field.type.kind === 'integer' || field.type.kind === 'number') return '0'
  if (field.type.kind === 'array') return '[]'
  if (field.type.kind === 'map') return 'null'
  if (field.type.kind === 'ref') {
    const target = schemaByName(model, field.type.name)
    if (target.kind === 'alias') return "''"
    return `new ${field.type.name}()`
  }
  return "''"
}

function arkNullValue(model, field) {
  if (field.nullable || field.type.kind === 'map') return 'null'
  return arkInitial(model, field)
}

function jsonTag(field) {
  if (field.nullable) return field.jsonName
  if (!field.required) return `${field.jsonName},omitempty`
  return field.jsonName
}

function goFieldType(field) {
  const base = goType(field.type)
  if (field.type.kind === 'array' || field.type.kind === 'map' || field.type.kind === 'json') {
    return base
  }
  if (!field.required || field.nullable) return `*${base}`
  return base
}

function goType(type) {
  switch (type.kind) {
    case 'string':
      return 'string'
    case 'integer':
      return 'int64'
    case 'number':
      return 'float64'
    case 'boolean':
      return 'bool'
    case 'ref':
      return type.name
    case 'array':
      return `[]${goType(type.item)}`
    case 'map':
      return `map[string]${goType(type.value)}`
    case 'json':
      return 'json.RawMessage'
    default:
      throw new Error(`unsupported Go type ${type.kind}`)
  }
}

function swiftFieldType(model, field) {
  const base = swiftTypeOf(model, field.type)
  if (!field.required || field.nullable) return `${base}?`
  return base
}

function swiftTypeOf(model, type) {
  switch (type.kind) {
    case 'string':
      return 'String'
    case 'integer':
      return 'Int'
    case 'number':
      return 'Double'
    case 'boolean':
      return 'Bool'
    case 'ref':
      return type.name
    case 'array':
      return `[${swiftTypeOf(model, type.item)}]`
    case 'map':
      return `[String: ${swiftTypeOf(model, type.value)}]`
    case 'json':
      return 'QlutchJSON'
    default:
      throw new Error(`unsupported Swift type ${type.kind}`)
  }
}

function kotlinFieldType(model, field) {
  const base = kotlinTypeOf(model, field.type)
  if (!field.required || field.nullable) return `${base}?`
  return base
}

function kotlinTypeOf(model, type) {
  switch (type.kind) {
    case 'string':
    case 'json':
      return 'String'
    case 'integer':
      return 'Long'
    case 'number':
      return 'Double'
    case 'boolean':
      return 'Boolean'
    case 'ref':
      return schemaByName(model, type.name).kind === 'alias' ? 'String' : type.name
    case 'array':
      return `List<${kotlinTypeOf(model, type.item)}>`
    case 'map':
      return `Map<String, ${kotlinTypeOf(model, type.value)}>`
    default:
      throw new Error(`unsupported Kotlin type ${type.kind}`)
  }
}

function schemaByName(model, name) {
  const found = model.schemas.find((schema) => schema.name === name)
  if (!found) throw new Error(`unknown schema ${name}`)
  return found
}

function modelUsesJSON(model) {
  for (const schema of model.schemas) {
    if (schema.kind !== 'object') continue
    for (const field of schema.fields) {
      if (field.type.kind === 'json') return true
    }
  }
  return false
}

function pathParamArgs(operation, lang) {
  return (operation.pathParams ?? []).map((param) => {
    if (lang === 'go') return `${param.name} string`
    if (lang === 'swift') return `${param.name}: String`
    if (lang === 'kotlin') return `${param.name}: String`
    return `${param.name}: string`
  })
}

function goPathExpr(operation) {
  const params = operation.pathParams ?? []
  if (params.length === 0) return JSON.stringify(operation.path)
  let expr = JSON.stringify(operation.path)
  for (const param of params) {
    expr = `strings.Replace(${expr}, "{${param.name}}", url.PathEscape(${param.name}), 1)`
  }
  return expr
}

function tsPathExpr(operation) {
  const params = operation.pathParams ?? []
  if (params.length === 0) return `'${operation.path}'`
  let path = operation.path
  for (const param of params) {
    path = path.replaceAll(`{${param.name}}`, `\${encodeURIComponent(${param.name})}`)
  }
  return `\`${path}\``
}

function swiftPathExpr(operation) {
  const params = operation.pathParams ?? []
  if (params.length === 0) return `"${operation.path}"`
  let path = operation.path
  for (const param of params) {
    path = path.replaceAll(
      `{${param.name}}`,
      `\\(${param.name}.addingPercentEncoding(withAllowedCharacters: .urlPathAllowed) ?? ${param.name})`,
    )
  }
  return `"${path}"`
}

function kotlinPathExpr(operation) {
  const params = operation.pathParams ?? []
  if (params.length === 0) return `"${operation.path}"`
  const [head, tail] = operation.path.split(`{${params[0].name}}`)
  return `"${head}" + java.net.URLEncoder.encode(${params[0].name}, java.nio.charset.StandardCharsets.UTF_8).replace("+", "%20") + "${tail}"`
}

function arkPathExpr(operation) {
  const params = operation.pathParams ?? []
  if (params.length === 0) return `'${operation.path}'`
  let path = operation.path
  for (const param of params) {
    path = path.replaceAll(`{${param.name}}`, `\${encodeURIComponent(${param.name})}`)
  }
  return `\`${path}\``
}

function headerPresent(operation, name) {
  return operation.headers.some((item) => item.name === name)
}

function headerRequired(operation, name) {
  return operation.headers.some((item) => item.name === name && item.required)
}

function operationNeedsMeta(operation) {
  return headerPresent(operation, 'X-Request-Id') || operation.auth !== 'none'
}

function exportWord(method) {
  const lower = method.toLowerCase()
  return lower.slice(0, 1).toUpperCase() + lower.slice(1)
}
